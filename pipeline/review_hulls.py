"""Write the yes/no review list for hulls the rules can't decide (#610).

Usage: python pipeline/review_hulls.py
Reads pipeline/out/ships.parsed.json (run parse_ships.py first), applies the inclusion rules and
any answers already in data/hull-decisions.json, and writes data/hull-review.md.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from dexpipe.inclusion import REVIEW_GROUPS, classify  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PARSED = ROOT / "pipeline" / "out" / "ships.parsed.json"
REVIEW = ROOT / "data" / "hull-review.md"


def main():
    records = json.loads(PARSED.read_text(encoding="utf-8"))
    names = {(r["era"], r["id"]): r for r in records}
    verdicts = classify(records)
    asks = [v for v in verdicts if v.status == "ask"]

    grouped, singles = {}, []
    for v in asks:
        for name, pattern, what, suggestion in REVIEW_GROUPS:
            if re.search(pattern, v.hull):
                grouped.setdefault(name, (what, suggestion, []))[2].append(v)
                break
        else:
            singles.append(v)

    def line(v):
        r = names[(v.era, v.hull)]
        refs = ", ".join(v.evidence[:3]) or "nothing else refers to it"
        return f"| {v.era} | `{v.hull}` | {r['name']} | {r['classification']['displayFamily']} | {v.reason} | {refs} |"

    out = [
        "# Hull review: yes or no?",
        "",
        "Generated by `pipeline/review_hulls.py`. Answer each **group** with yes or no (plus any exceptions), "
        "and each **single hull** with yes or no. Answers go into `data/hull-decisions.json`, "
        "and the pipeline never asks the same question twice.",
        "",
        f"Status: {Counter(v.status for v in verdicts)}",
        "",
        "## Groups",
        "",
    ]
    for gi, (name, (what, suggestion, items)) in enumerate(grouped.items(), start=1):
        out += [f"### G{gi}. {name} ({len(items)} hulls)", "", f"{what}. Suggested: **{suggestion}**.", "",
                "| Era | Hull | Name | Class | Why it's here | Referenced by |", "|---|---|---|---|---|---|"]
        out += [line(v) for v in sorted(items, key=lambda v: (v.era, v.hull))]
        out.append("")
    out += ["## Single hulls", "", "| # | Era | Hull | Name | Class | Why it's here | Referenced by |", "|---|---|---|---|---|---|---|"]
    for i, v in enumerate(sorted(singles, key=lambda v: (v.era, v.hull)), start=1):
        out.append(f"| S{i} " + line(v)[1:])
    REVIEW.write_text("\n".join(out) + "\n", encoding="utf-8")

    print(f"{len(asks)} hulls to review: {len(grouped)} groups, {len(singles)} single hulls")
    for name, (_, suggestion, items) in grouped.items():
        print(f"  {name}: {len(items)} (suggested {suggestion})")
    print(f"Wrote {REVIEW}")


if __name__ == "__main__":
    main()
