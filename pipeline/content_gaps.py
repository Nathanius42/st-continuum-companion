"""Report how complete each Dex entry is, so every ship ends up with the same level of detail.

Usage: python pipeline/content_gaps.py
Assembles every entry (run parse_ships.py first) and writes:
  data/content-gaps.md    readable summary and per-ship checklist
  data/content-gaps.json  the same, for the follow-up content pass to work through
"""
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from dexpipe.assemble import assemble  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PARSED = ROOT / "pipeline" / "out" / "ships.parsed.json"
OUT_MD = ROOT / "data" / "content-gaps.md"
OUT_JSON = ROOT / "data" / "content-gaps.json"

PLACEHOLDER = re.compile(r"\b(tbd|todo|placeholder|lorem|to be written|n/?a)\b|^\s*-\s*$", re.I)
MIN_SUMMARY = 60  # characters; shorter summaries are flagged as thin

# What every entry should have, in report order: (key, label).
CHECKS = [
    ("name", "Proper name (not a code)"),
    ("subtitle", "Subtitle"),
    ("description", "Build description"),
    ("lead", "Description lead line"),
    ("crew", "Crew complement"),
    ("armament", "Armament"),
    ("defences", "Defences"),
    ("prerequisites", "Prerequisites"),
    ("summary", "Summary"),
    ("summary-thin", f"Summary of at least {MIN_SUMMARY} characters"),
    ("summary-unique", "Summary written for this ship (not shared generic text)"),
    ("size", "Dimensions"),
    ("roles", "AI roles"),
    ("research", "RequiredResearch field present (buildable ships)"),
    ("icon", "Icon in the mod"),
]
LATER = {"turntable": "Turntable render (#457)"}
OUT_CREDITS = ROOT / "data" / "credits-missing.md"


# Entries that show no crew (#914): structures (outposts, starbases, civilian stations,
# turrets, and Regula I, the game's one Megalith), and the Crystalline Entity, a creature.
STRUCTURE_FAMILIES = {"Platform", "Megalith"}
NO_CREW = {"zzz_TNG_crystallineentity"}


def is_structure(e: dict) -> bool:
    return e["classification"]["displayFamily"] in STRUCTURE_FAMILIES or e["id"] in NO_CREW


def gaps_for(e: dict, summary_owners: dict) -> list[str]:
    g = []
    if not e["name"] or e["name"].startswith("$"):
        g.append("name")
    if not e["subtitle"] or PLACEHOLDER.search(e["subtitle"] or ""):
        g.append("subtitle")
    d = e["description"]
    if d is None:
        g += ["description", "lead", "crew", "armament", "defences", "prerequisites", "summary"]
    else:
        if not d["lead"]:
            g.append("lead")
        if d["crew"] is None and not is_structure(e):
            g.append("crew")
        for key in ("armament", "defences", "prerequisites"):
            if not d[key] or all(PLACEHOLDER.search(x) for x in d[key]):
                g.append(key)
        s = d["summary"] or ""
        if not s or PLACEHOLDER.search(s):
            g.append("summary")
        else:
            if len(s) < MIN_SUMMARY:
                g.append("summary-thin")
            if len(summary_owners[s.strip().lower()]) > 1:
                g.append("summary-unique")
    if e["stats"]["length"] is None or e["stats"]["width"] is None:
        g.append("size")
    if not e["roles"]:
        g.append("roles")
    # An empty RequiredResearch means "none needed" and is fine; only a missing field is a gap.
    if "buildable" in e["availability"] and not e["_pipeline"]["researchFieldPresent"]:
        g.append("research")
    if not e["media"]["icon"]:
        g.append("icon")
    return g


def main():
    records = json.loads(PARSED.read_text(encoding="utf-8"))
    entries, _ = assemble(records)

    summary_owners = defaultdict(list)
    for e in entries:
        s = (e["description"] or {}).get("summary") if e["description"] else None
        if s:
            summary_owners[s.strip().lower()].append(e["id"])

    per_ship, field_counts, era_counts = [], Counter(), defaultdict(Counter)
    for e in entries:
        g = gaps_for(e, summary_owners)
        for key in g:
            field_counts[key] += 1
            era_counts[e["era"]][key] += 1
        if g:
            item = {"era": e["era"], "id": e["id"], "name": e["name"], "faction": e["faction"],
                    "availability": e["availability"], "gaps": g, "dexWritten": e["_pipeline"]["dexWritten"]}
            if "summary-unique" in g:
                s = e["description"]["summary"].strip().lower()
                item["sharesSummaryWith"] = [x for x in summary_owners[s] if x != e["id"]]
            per_ship.append(item)

    complete = len(entries) - len(per_ship)
    eras = ["ENT", "TOS", "TMP", "TNG"]
    md = [
        "# Content gaps",
        "",
        "Generated by `pipeline/content_gaps.py`. Every Dex entry should carry the same level of detail; "
        "this lists what's missing so a follow-up content pass can fill it. Regenerate after each pipeline change.",
        "",
        f"**{len(entries)} entries: {complete} complete, {len(per_ship)} with gaps.**",
        "",
        "## By field",
        "",
        "| Field | Missing | " + " | ".join(eras) + " |",
        "|---|---|" + "---|" * len(eras),
    ]
    for key, label in CHECKS:
        md.append(f"| {label} | {field_counts[key]} | " + " | ".join(str(era_counts[x][key]) for x in eras) + " |")
    md += ["", "Not yet attached for any ship (later pipeline steps): " + ", ".join(LATER.values()) + ".", ""]

    # Where the text came from (#640): the mod's build lists, or the Dex's own overlay in data/content/.
    dex = [e for e in entries if e["_pipeline"]["dexWritten"]]
    field_sources = Counter(f for e in dex for f in e["_pipeline"]["dexWritten"])
    md += ["## Dex-written content", "",
           f"{len(dex)} entries carry text written for the Dex (`data/content/*.json`, merged by `dexpipe/content.py`) "
           "rather than taken from the mod. Fields: " + ", ".join(f"{k} {v}" for k, v in field_sources.most_common()) + ".",
           "Anything here that would also improve the game can be offered back to the mod.", ""]

    by_kind = defaultdict(list)
    for item in per_ship:
        kind = "no build description" if "description" in item["gaps"] else "partial"
        by_kind[kind].append(item)
    labels = dict(CHECKS)
    for kind, items in by_kind.items():
        md += [f"## Ships with {kind} ({len(items)})", "", "| Era | Ship | Name | How it appears | Missing |", "|---|---|---|---|---|"]
        for it in sorted(items, key=lambda x: (x["era"], x["id"])):
            missing = ", ".join(labels[g] for g in it["gaps"] if not (kind == "no build description" and g in
                                                                        ("lead", "crew", "armament", "defences", "prerequisites", "summary")))
            if it.get("sharesSummaryWith"):
                missing += f" (same text as {', '.join(it['sharesSummaryWith'][:3])})"
            md.append(f"| {it['era']} | `{it['id']}` | {it['name']} | {', '.join(it['availability'])} | {missing} |")
        md.append("")

    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")

    # Entries whose model has no readme naming its authors (#427), for asking the team.
    uncredited = [e for e in entries if not e["credits"]["authors"]]
    cm = ["# Entries without model credits", "",
          "Generated by `pipeline/content_gaps.py`. These entries have no creator in the mod's ReadMe.docx credits table and no readme naming their "
          "authors (#427, #935). Add what the team knows to "
          "`data/credits.source.json`.", "",
          f"**{len(uncredited)} of {len(entries)} entries.**", "",
          "| Era | Ship | Name | Faction |", "|---|---|---|---|"]
    for e in sorted(uncredited, key=lambda x: (x["era"], x["faction"], x["id"])):
        cm.append(f"| {e['era']} | `{e['id']}` | {e['name']} | {e['faction']} |")
    OUT_CREDITS.write_text("\n".join(cm) + "\n", encoding="utf-8")
    OUT_JSON.write_text(json.dumps({"entries": len(entries), "complete": complete, "byField": dict(field_counts),
                                    "ships": per_ship}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(entries)} entries: {complete} complete, {len(per_ship)} with gaps")
    for key, label in CHECKS:
        if field_counts[key]:
            print(f"  {label}: {field_counts[key]}")
    print(f"Wrote {OUT_MD} and {OUT_JSON}")


if __name__ == "__main__":
    main()
